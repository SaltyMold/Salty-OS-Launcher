#!/usr/bin/env python3
"""Turn a themes.zip into src/themes_data.c, the data written to the theme area.

  themes_to_c.py THEMES.zip OUT.c [--generator generate_theme.py]

1. unzip THEMES.zip
2. every folder containing a name.txt or palette.txt is a theme: they are all
   given to generate_theme.py (Salty-OS, themes/generate_theme.py; needs lz4 and
   Pillow or pypng)
3. the generated theme area becomes a C array (only the used part: the rest of
   the 1.5 MiB area is zero padding)
"""
import argparse
import re
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path


def fail(message):
    sys.exit(f"error: {message}")


def find_themes(root):
    found = {p.parent for pattern in ("name.txt", "palette.txt") for p in root.rglob(pattern)}
    return sorted(p for p in found if "__MACOSX" not in p.parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("zip", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--generator", type=Path, default=Path(__file__).with_name("generate_theme.py"))
    args = parser.parse_args()

    if not args.generator.is_file():
        fail(f"{args.generator} not found (copy Salty-OS themes/generate_theme.py there, or use --generator)")

    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        with zipfile.ZipFile(args.zip) as z:
            z.extractall(tmp / "themes")
        themes = find_themes(tmp / "themes")
        if not themes:
            fail("no theme folder (with a name.txt or palette.txt) in the zip")

        area = tmp / "theme_area.bin"
        run = subprocess.run(
            [sys.executable, str(args.generator.resolve()), *map(str, themes), "-o", str(area)],
            capture_output=True, text=True,
        )
        sys.stdout.write(run.stdout)
        if run.returncode:
            fail(run.stderr.strip() or "generate_theme.py failed")

        used = re.search(r"used (\d+)/", run.stdout)
        if not used:
            fail("could not read the used size from generate_theme.py")
        blob = area.read_bytes()[: (int(used.group(1)) + 3) // 4 * 4]  # multiple of 4

    lines = []
    for i in range(0, len(blob), 16):
        lines.append("    " + ",".join(f"0x{b:02x}" for b in blob[i : i + 16]) + ",")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        "// Generated by scripts/themes_to_c.py from themes.zip. Do not edit.\n"
        '#include "themes_data.h"\n\n'
        f"const uint32_t themes_size = {len(blob)};\n"
        f"const uint8_t themes_data[{len(blob)}] __attribute__((aligned(4))) = {{\n"
        + "\n".join(lines)
        + "\n};\n"
    )
    print(f"{args.output}: {len(themes)} theme(s), {len(blob)} bytes")


if __name__ == "__main__":
    main()
